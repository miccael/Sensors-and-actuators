	rcall OWWriteByteDS1822
	ldi r16, 0b00011111     // [CONFIGURATION REGISTER] 9-bit resolution, 93.75ms conversion time
	rcall OWWriteByteDS1822

	rcall OWResetDS1822
	ldi r16, 0xCC     //skip ROM
