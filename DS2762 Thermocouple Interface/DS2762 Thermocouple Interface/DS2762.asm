SENSOR_DS2762:

	

	

	rcall OWResetDS2762
	ldi r16, 0xCC     //skip ROM
	rcall OWWriteByteDS2762
	ldi r16, 0x6C     //Master issues a Write Data command.
	rcall OWWriteByteDS2762
	ldi r16, 0x00     //Master sends the starting memory address.
	rcall OWWriteByteDS2762
	ldi r16, 0b00000001    //DE=1 bit 0 [pin 3], Protection Register Format  Writing a 0 to this bit disables charging (DE output high, external charge FET off)
	rcall OWWriteByteDS2762
	


	rcall OWResetDS2762
	ldi r16, 0xCC     //skip ROM
	rcall OWWriteByteDS2762
	ldi r16, 0x69     //Master issues a Read Data command.
	rcall OWWriteByteDS2762
	ldi r16, 0x0E     //Master sends the starting memory address.
	rcall OWWriteByteDS2762
	rcall OWReadByteDS2762 //Read 1 Byte (Current Register MSB)
	;rcall OWReadByteDS2762

	mov DATA, r16
	
	

	
